// // *Задача 4.
// // Создайте программу, которая рассчитывает стоимость доставки посылки, основываясь на весе и типе доставки. Программа должна запрашивать у пользователя данные с помощью prompt и выводить результат через alert.

const weight = +prompt("Ведите вес посылки (в килограммах)", "0");
const type = prompt(
  `"Ведите тип доставки. Допустимые варианты: "Стандарт", "Экспресс", "Премиум"`,
  "",
);

let baseCost;
let coefficient;
let priсe;

if (weight > 0) {
  if (type === "Стандарт" || type === "Экспресс" || type === "Премиум") {
    baseCost = weight < 1 ? 5 : weight <= 5 ? 10 : 15;

    switch (type) {
      case "Стандарт":
        coefficient = 1;
        break;
      case "Экспресс":
        coefficient = 1.5;
        break;
      case "Премиум":
        coefficient = 2;
        break;
    }

    priсe = baseCost * coefficient;
  } else alert("Неверный тип доставки");
} else alert("Некорректный вес посылки");
if (priсe == undefined) {
  alert("Где-то указаны некоректные данные!");
} else alert(`Итоговая стоимость доставки: ${priсe}$`);
