const number = +prompt("Ведите любое целое число", "0");

if (isNaN(number)) {
  alert("Введено некоректное знчение!");
} else if (number % 2) {
  alert(`Число ${number} нечетное!`);
} else {
  alert(`Число ${number} четное!`);
}

